def _sanitize_name(raw):
    """v71: a DISPLAY name for an entry (never a path) - strip control
    characters / separators, cap the length. Empty input -> None."""
    if not isinstance(raw, str):
        return None
    cleaned = re.sub(r"[\x00-\x1f\x7f]", " ", raw).strip()
    if not cleaned:
        return None
    return cleaned[:MAX_NAME_CHARS]


def _sanitize_tab(raw):
    """v79: the display-group (tab) name of an entry - metadata only, never a
    path; the ?tab= clear parameter is URL-encoded by the client, so any
    printable text is fine. Control characters are stripped, the result is
    trimmed and capped. Empty input -> None (= ungrouped / "All")."""
    if not isinstance(raw, str):
        return None
    cleaned = re.sub(r"[\x00-\x1f\x7f]", " ", raw).strip()
    if not cleaned:
        return None
    return cleaned[:MAX_TAB_CHARS]


def _sanitize_node_meta(raw):
    """v99: PREVIEW metadata of a node-fragment entry ("nodes" type only).
    The web panel computes it ONCE per fragment at capture time (or lazily
    for old entries) and stores it alongside the item so the CARD never has
    to re-parse the raw JSON, and file-backed fragments (>100 KB) become
    fully described too. WHITELIST rebuild: only the known keys survive,
    every string is control-stripped and capped, every counter clamped to a
    sane range; the rebuilt object must fit NODE_META_MAX_BYTES or the whole
    thing is dropped (None - the client falls back to parsing on demand).
    The metadata NEVER participates in the content hash (that is computed
    from the text alone) and never touches the stored fragment JSON."""
    if not isinstance(raw, dict):
        return None
    def _str(v, cap):
        if not isinstance(v, str):
            return None
        cleaned = re.sub(r"[\x00-\x1f\x7f]", " ", v).strip()
        return cleaned[:cap] if cleaned else None
    def _int(v, lo, hi):
        try:
            return max(lo, min(hi, int(v)))
        except (TypeError, ValueError):
            return None
    meta = {"schema": 1}
    nc = _int(raw.get("nodeCount"), 1, 100_000)
    if nc is None:
        return None  # a fragment meta without a node count is meaningless
    meta["nodeCount"] = nc
    # linkCount: null = the clipboard shape did not let us count reliably -
    # the card must NOT show "0 links" for an unknown number.
    if raw.get("linkCount") is None:
        meta["linkCount"] = None
    else:
        lc = _int(raw.get("linkCount"), 0, 500_000)
        if lc is None:
            return None
        meta["linkCount"] = lc
    gc = _int(raw.get("groupCount"), 0, 10_000)
    if gc is None:
        return None
    meta["groupCount"] = gc
    types = []
    rt = raw.get("types")
    if isinstance(rt, list):
        for t in rt:
            if not isinstance(t, (list, tuple)) or len(t) != 2:
                continue
            name = _str(t[0], NODE_META_MAX_STR)
            # a zero/negative occurrence count is meaningless - drop the entry
            # (a clamp would FABRICATE occurrences that never existed)
            cnt = _int(t[1], 0, 100_000)
            if name and cnt:
                types.append([name, cnt])
            if len(types) >= NODE_META_MAX_TYPES:
                break
    meta["types"] = types
    groups = []
    rg = raw.get("groups")
    if isinstance(rg, list):
        for g in rg:
            if isinstance(g, str):
                g = {"title": g}
            if not isinstance(g, dict):
                continue
            title = _str(g.get("title"), NODE_META_MAX_STR)
            if not title:
                continue
            entry = {"title": title}
            color = _str(g.get("color"), 32)
            if color:
                entry["color"] = color
            groups.append(entry)
            if len(groups) >= NODE_META_MAX_GROUPS:
                break
    meta["groups"] = groups
    st = _str(raw.get("singleTitle"), 2 * NODE_META_MAX_STR)
    if st:
        meta["singleTitle"] = st
    try:
        blob = json.dumps(meta, ensure_ascii=False)
    except (TypeError, ValueError):
        return None
    if len(blob.encode("utf-8", "ignore")) > NODE_META_MAX_BYTES:
        return None
    return meta


def _blob_type_for(ext):
    """v71: index `type` for a stored blob extension."""
    if ext in _IMG_EXT:
        return "image"
    if ext in _VID_EXT:
        return "video"
    if ext in _AUD_EXT:
        return "audio"
    return "file"


def _touch_dup(items, content_hash, wf=None):
    """If an entry with this hash exists, move it to the top (fresh created)
    and return (entry, True). Returns None when there is no duplicate."""
    idx = next((i for i, x in enumerate(items) if x.get("hash") == content_hash), None)
    if idx is None:
        return None
    old = items.pop(idx)
    old["created"] = int(time.time())
    items.insert(0, old)
    _write_index(items, wf)
    return old, True


@PromptServer.instance.routes.get("/settings_hub/stack")
async def stack_get(request):
    wf, err = _wf_from(request)
    if err is not None:
        return err
    # A workflow store that was never written simply reads as empty - the
    # panel shows a fresh stack for a fresh workflow (no 404 noise).
    return web.json_response({"ok": True, "items": _read_index(wf)})



"""v70: server-side storage for the Settings Hub Paste Stack.

The stack is a floating clipboard-history panel (web/stack.js). Its entries
live IN THE COMFYUI PROCESS FILESYSTEM - not in the browser - so the stack
travels with the ComfyUI folder (portability, owner decision 2026-11-08):
it is shared by every origin (localhost / 127.0.0.1 / LAN), browser and
profile, and survives site-data wipes.

Layout under the user directory:

    <user>/settings_hub/stack/index.json   - metadata, top-first order:
        [{id, type, created, hash, size, text?, file?, name?, tags?,
          pinned?, uses?}]
    <user>/settings_hub/stack/items/<id>.<ext> - blobs (any kind)

v77 adds SCOPED stores: every route accepts an optional `?wf=<id>` query
parameter. With it the handler operates on a per-workflow store instead of
the shared one:

    <user>/settings_hub/stack/workflows/<id>/index.json
    <user>/settings_hub/stack/workflows/<id>/items/<id>.<ext>

The id is generated by the web panel and stored in the workflow's
`extra.settingshubStackId`, so it is serialized INTO the workflow file and
the stack binding travels with it (owner contract: "the stack is saved into
the workflow"). The payloads stay server-side; TEXT entries are additionally
mirrored into the workflow file by the client (extra.settingshubStack) so
they can be rehydrated when the server store is empty (workflow moved to
another machine, user folder wiped). Switching the scope never copies or
moves entries - each scope keeps its own (AGENTS.md 5.1 rule 7).

v80 adds REORDER (owner request: "a toggle button that enables a move mode -
sort the order of the stack entries"): POST /settings_hub/stack/reorder
takes {order: [id, ...]} - the FULL new order, top-first - and rewrites the
index in that order. Entries NOT mentioned in the payload keep their
relative order at the END (a stale client can never lose them), unknown
ids are ignored, the blobs and every other field are untouched. Reordering
is purely a re-arrangement - it NEVER deletes entries and does not touch
created/pinned/tab metadata (AGENTS.md 5.1 rule 9/10). ?wf= scopes it.

v79 adds TABS (owner request: "tabs to fill the stack for different tasks -
grouping"): every entry may carry a `tab` display-group name (sanitized,
<= 48 chars, purely metadata - it changes NO path, hash or cap). The view
side (All + one view per tab) lives in web/stack.js; the server only stores
and patches the field. POST item/image/file accept it at creation (the
capture lands straight in the open tab), PATCH sets/clears it (rename and
"move back to All" are client loops over this), and POST clear accepts
?tab=<name> to wipe ONLY that tab's entries - the other tabs and the
ungrouped entries stay. Removing/renaming a tab NEVER deletes entries
(AGENTS.md 5.1 rule 9).

Routes (registered at import, PromptServer aiohttp, same style as
media_list.py; the SettingsHub node class itself stays a stub and these
routes never run during a queue):

    GET    /settings_hub/stack             -> {ok, items}      ?wf=<id> = scope
    GET    /settings_hub/stack/health      -> {ok, version, dir, writable,
                                              items, workflows} (v76: the panel
                                              probes this FIRST and tells the
                                              user exactly why storage is down:
                                              routes missing / not writable /
                                              web-vs-py version mismatch; v77
                                              adds the workflows store count)
    POST   /settings_hub/stack/item        -> JSON {type:"text", text, name?, tab?}  add text
    POST   /settings_hub/stack/image       -> raw bytes, ?ext=png|jpg|...&tab=  add image
    POST   /settings_hub/stack/file        -> raw bytes, ?ext=&name=&tab=       add ANY
                                            file (v71: video/audio/text/
                                            binary cards from drag&drop or
                                            the OS-clipboard helper)
    DELETE /settings_hub/stack/item/{id}   -> remove one entry (+ blob)
    POST   /settings_hub/stack/clear       -> wipe entries + blobs (?tab=<name>
                                            v79: only that tab's entries)
    GET    /settings_hub/stack/file/{name} -> serve a stored blob   ?wf=<id>

All mutating/listing routes honour ?wf= (v77); without it they behave
exactly like the pre-v77 shared store, so older panels keep working.

v71 also adds POST /settings_hub/stack/patch (rename/tags/pin/uses - the
snippet engine of v72) in the same file below.

v80 also adds POST /settings_hub/stack/reorder - the client's move mode
sends the full new id order after a drag; the server reorders the index
and answers with the rewritten list (the client mirrors that truth).

Safety: names are validated against ^[A-Za-z0-9._-]{1,120}$ and resolved
INSIDE the items directory (no traversal); writes are size-capped; the
index is written atomically (tmp + os.replace); every mutation takes an
asyncio.Lock (aiohttp handlers interleave on one event loop).

Dedup: each entry carries a sha1-based hash of its content. Re-adding the
same content MOVES the existing entry to the top (fresh `created`) instead
of stacking a copy - exactly the Nougan semantics.

Eviction: hard caps of MAX_ITEMS entries / MAX_TOTAL_BYTES (configurable
client max applies BEFORE these server-side guards; the client deletes its
oldest first). The server drops the OLDEST tail entries (pinned excluded,
pinned arrives in v72) and unlinks their blobs.
"""
import asyncio
import hashlib
import json
import os
import re
import time
import uuid

from server import PromptServer
from aiohttp import web

try:
    import folder_paths
except Exception:  # pragma: no cover - folder_paths always exists in ComfyUI
    folder_paths = None

# ---------------------------------------------------------------------------
# Limits (server-side absolute guards; the frontend may enforce smaller ones)
# ---------------------------------------------------------------------------

MAX_ITEMS = 500
MAX_TOTAL_BYTES = 200 * 1024 * 1024
MAX_TEXT_CHARS = 1_000_000
MAX_IMAGE_BYTES = 25 * 1024 * 1024
MAX_BLOB_BYTES = MAX_IMAGE_BYTES  # v71: the same cap applies to any blob kind
TEXT_INLINE_LIMIT = 100 * 1024  # larger texts become files too
MAX_NAME_CHARS = 120            # display name of an entry (v71)
MAX_TAGS = 8                    # v72: per-entry tag cap
MAX_TAG_CHARS = 24              # v72: per-tag cap
MAX_TAB_CHARS = 48              # v79: display-group (tab) name cap

_IMG_EXT = {
    "png": "image/png",
    "jpg": "image/jpeg",
    "jpeg": "image/jpeg",
    "webp": "image/webp",
    "gif": "image/gif",
    "bmp": "image/bmp",
}
_TEXT_EXT = {"txt", "md", "json", "csv", "log", "py", "js", "css", "html", "xml", "yml", "yaml"}
# v71: blob kinds the generic file route accepts, with their content types.
_VID_EXT = {
    "mp4": "video/mp4", "webm": "video/webm", "mov": "video/quicktime",
    "mkv": "video/x-matroska", "avi": "video/x-msvideo",
    "m4v": "video/x-m4v", "ogv": "video/ogg",
}
_AUD_EXT = {
    "mp3": "audio/mpeg", "wav": "audio/wav", "ogg": "audio/ogg",
    "flac": "audio/flac", "aac": "audio/aac", "m4a": "audio/mp4",
    "opus": "audio/opus",
}
_DOC_MIME = {
    "txt": "text/plain", "md": "text/markdown", "json": "application/json",
    "csv": "text/csv", "log": "text/plain", "pdf": "application/pdf",
}
_FILE_MIME = {**_IMG_EXT, **_VID_EXT, **_AUD_EXT, **_DOC_MIME}
_ALL_BLOB_EXT = set(_FILE_MIME) | {"zip", "safetensors"}
_NAME_RE = re.compile(r"^[A-Za-z0-9._-]{1,120}$")
_ID_RE = re.compile(r"^[a-f0-9]{8,32}$")
# v77: workflow scope ids - generated by the client ("wf-<base36>-<base36>"),
# stored in the workflow file (extra.settingshubStackId). Strict charset
# keeps the id safe to embed in a path segment (no dots -> no traversal).
_WF_RE = re.compile(r"^[A-Za-z0-9_-]{1,64}$")

_lock = asyncio.Lock()


# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------

def _stack_root(wf=None):
    """<user-dir>/settings_hub/stack - or, with a workflow scope (v77),
    <user-dir>/settings_hub/stack/workflows/<id>. folder_paths
    .get_user_directory() is the canonical user dir (default <ComfyUI>/user);
    never hardcode a path. `wf` MUST be validated with _WF_RE by the caller
    (_wf_from) - the charset alone already rules out traversal."""
    base = None
    if folder_paths is not None:
        fn = getattr(folder_paths, "get_user_directory", None)
        if callable(fn):
            try:
                base = fn()
            except Exception:
                base = None
    if not isinstance(base, str) or not base:
        base = os.path.join(os.getcwd(), "user")
    root = os.path.join(base, "settings_hub", "stack")
    if wf:
        root = os.path.join(root, "workflows", wf)
    return root


def _items_dir(wf=None):
    return os.path.join(_stack_root(wf), "items")


def _index_path(wf=None):
    return os.path.join(_stack_root(wf), "index.json")


def _ensure_dirs(wf=None):
    try:
        os.makedirs(_items_dir(wf), exist_ok=True)
    except Exception:
        pass


def _unlink_blob(name, wf=None):
    if not isinstance(name, str) or not _NAME_RE.match(name):
        return
    try:
        items_dir = _items_dir(wf)
        p = os.path.join(items_dir, name)
        if os.path.abspath(p).startswith(os.path.abspath(items_dir) + os.sep):
            os.unlink(p)
    except OSError:
        pass


def _wf_from(request):
    """v77: parse the ?wf= scope of a request. Returns (wf, error_response);
    exactly one of the two is None. No wf parameter -> (None, None) = the
    shared store. A MALFORMED wf must never silently fall through to the
    shared store - that would cross-contaminate the scopes."""
    wf = request.query.get("wf")
    if not wf:
        return None, None
    if not _WF_RE.match(wf):
        return None, web.json_response({"ok": False, "error": "bad wf"}, status=400)
    return wf, None


def _workflow_count():
    """v77: how many per-workflow stores exist (health reporting)."""
    try:
        root = os.path.join(_stack_root(), "workflows")
        return sum(1 for n in os.listdir(root)
                   if _WF_RE.match(n) and os.path.isdir(os.path.join(root, n)))
    except Exception:
        return 0


# ---------------------------------------------------------------------------
# Index read/write (atomic)
# ---------------------------------------------------------------------------

def _read_index(wf=None):
    try:
        with open(_index_path(wf), "r", encoding="utf-8") as f:
            data = json.load(f)
        if isinstance(data, list):
            return [it for it in data if isinstance(it, dict) and isinstance(it.get("id"), str)]
    except Exception:
        pass
    return []


def _write_index(items, wf=None):
    _ensure_dirs(wf)
    tmp = _index_path(wf) + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(items, f, ensure_ascii=False)
    os.replace(tmp, _index_path(wf))


# ---------------------------------------------------------------------------
# Mutations (call under _lock)
# ---------------------------------------------------------------------------

def _hash_bytes(b):
    return hashlib.sha1(b).hexdigest()[:16]


def _entry_size(it):
    if it.get("type") == "text":
        return len(it.get("text", "").encode("utf-8", "ignore"))
    return int(it.get("size", 0) or 0)


def _evict(items, wf=None):
    """Drop the oldest tail until count/size caps hold; pinned entries are
    reserved (the field arrives in v72, guarded here already). The caps are
    PER STORE (v77): every workflow scope gets its own budget."""
    def droppable():
        alive = [it for it in items if not it.get("pinned")]
        return alive[-1] if alive else None

    while len(items) > MAX_ITEMS:
        victim = droppable()
        if victim is None:
            break
        items.remove(victim)
        _unlink_blob(victim.get("file"), wf)
    total = sum(_entry_size(it) for it in items)
    while total > MAX_TOTAL_BYTES:
        victim = droppable()
        if victim is None:
            break
        items.remove(victim)
        _unlink_blob(victim.get("file"), wf)
        total -= _entry_size(victim)


# ---------------------------------------------------------------------------
# Handlers
# ---------------------------------------------------------------------------

def _sanitize_name(raw):
    """v71: a DISPLAY name for an entry (never a path) - strip control
    characters / separators, cap the length. Empty input -> None."""
    if not isinstance(raw, str):
        return None
    cleaned = re.sub(r"[\x00-\x1f\x7f]", " ", raw).strip()
    if not cleaned:
        return None
    return cleaned[:MAX_NAME_CHARS]


def _sanitize_tab(raw):
    """v79: the display-group (tab) name of an entry - metadata only, never a
    path; the ?tab= clear parameter is URL-encoded by the client, so any
    printable text is fine. Control characters are stripped, the result is
    trimmed and capped. Empty input -> None (= ungrouped / "All")."""
    if not isinstance(raw, str):
        return None
    cleaned = re.sub(r"[\x00-\x1f\x7f]", " ", raw).strip()
    if not cleaned:
        return None
    return cleaned[:MAX_TAB_CHARS]


def _blob_type_for(ext):
    """v71: index `type` for a stored blob extension."""
    if ext in _IMG_EXT:
        return "image"
    if ext in _VID_EXT:
        return "video"
    if ext in _AUD_EXT:
        return "audio"
    return "file"


def _touch_dup(items, content_hash, wf=None):
    """If an entry with this hash exists, move it to the top (fresh created)
    and return (entry, True). Returns None when there is no duplicate."""
    idx = next((i for i, x in enumerate(items) if x.get("hash") == content_hash), None)
    if idx is None:
        return None
    old = items.pop(idx)
    old["created"] = int(time.time())
    items.insert(0, old)
    _write_index(items, wf)
    return old, True


@PromptServer.instance.routes.get("/settings_hub/stack")
async def stack_get(request):
    wf, err = _wf_from(request)
    if err is not None:
        return err
    # A workflow store that was never written simply reads as empty - the
    # panel shows a fresh stack for a fresh workflow (no 404 noise).
    return web.json_response({"ok": True, "items": _read_index(wf)})



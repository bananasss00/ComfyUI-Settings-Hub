@PromptServer.instance.routes.post("/settings_hub/stack/root")
async def stack_root_set(request):
    """Re-point the storage root. Body JSON {path}: an empty string or
    whitespace = back to the default; otherwise an ABSOLUTE folder path
    (~ expanded, pasted quotes stripped). The folder is created and probed
    writable BEFORE the switch. Entries are NEVER moved: the new root
    starts empty, the old one keeps its files (AGENTS.md 5.1 rule 7)."""
    try:
        body = await request.json()
    except Exception:
        return web.json_response({"ok": False, "error": "bad json"}, status=400)
    # The "path" key must be EXPLICIT (same philosophy as the clear route's
    # present-but-empty ?tab= error): an accidental/blank body must not reset
    # the root by hiding behind a missing value.
    raw = body.get("path") if isinstance(body, dict) else None
    if not isinstance(raw, str):
        return web.json_response({"ok": False, "error": "path must be a string"}, status=400)
    path, err = _clean_root_candidate(raw)
    if err:
        return web.json_response({"ok": False, "error": err}, status=400)
    global _root_custom
    async with _lock:
        if path:
            if not _probe_writable(path):
                return web.json_response(
                    {"ok": False, "error": "folder is not writable: " + path},
                    status=400)
            _root_custom = path
        else:
            _root_custom = None
        saved = _save_root_override()
    root = _stack_root()
    return web.json_response({
        "ok": True,
        "saved": saved,
        "root": root,
        "custom": _root_custom,
        "default": os.path.join(_user_dir(), "settings_hub", "stack"),
        "writable": _probe_writable(root),
    })


@PromptServer.instance.routes.post("/settings_hub/stack/item")
async def stack_add_text(request):
    """Add a TEXT entry. Body: JSON {text}. Text lives inline in the index
    unless it exceeds TEXT_INLINE_LIMIT - then it is stored as a .txt blob.
    v96: the body may carry `type` - "nodes" marks the text as a NODE
    FRAGMENT (a canvas-clipboard selection copied in the ComfyUI graph: the
    web panel pastes it back through the native canvas.pasteFromClipboard).
    The allowlist keeps the index honest; an absent/unknown type stays
    "text" (an old web build never sends the key, a newer one degrades the
    same way against an old py)."""
    try:
        body = await request.json()
    except Exception:
        return web.json_response({"ok": False, "error": "bad json"}, status=400)
    text = body.get("text") if isinstance(body, dict) else None
    if not isinstance(text, str) or not text.strip():
        return web.json_response({"ok": False, "error": "empty text"}, status=400)
    if len(text) > MAX_TEXT_CHARS:
        return web.json_response({"ok": False, "error": "text too large"}, status=413)
    name = _sanitize_name(body.get("name")) if isinstance(body, dict) else None
    tab = _sanitize_tab(body.get("tab")) if isinstance(body, dict) else None
    # v96: entry type - "nodes" = a node-fragment JSON, "text" = everything else
    entry_type = body.get("type") if isinstance(body, dict) else None
    if entry_type not in ("text", "nodes"):
        entry_type = "text"
    # v99: optional PREVIEW metadata of a node fragment (aggregated types /
    # groups / counts). Accepted for "nodes" entries only; sanitized to a
    # bounded whitelist - junk or oversize is dropped and the card falls back
    # to its parse-on-demand path. NEVER part of the content hash.
    node_meta = None
    if entry_type == "nodes" and isinstance(body, dict) and "nodeMeta" in body:
        node_meta = _sanitize_node_meta(body.get("nodeMeta"))
    wf, err = _wf_from(request)
    if err is not None:
        return err
    size = len(text.encode("utf-8", "ignore"))
    async with _lock:
        items = _read_index(wf)
        h = _hash_bytes(text.encode("utf-8"))
        dup = _touch_dup(items, h, wf)
        if dup is not None:
            # v71: a fresh drop of the same content may carry a better name.
            if name and not dup[0].get("name"):
                dup[0]["name"] = name
                _write_index(items, wf)
            # v79: re-adding into a tab groups the existing entry too - but a
            # tab already on the entry is NEVER overridden by a re-capture.
            if tab and not dup[0].get("tab"):
                dup[0]["tab"] = tab
                _write_index(items, wf)
            # v99: a re-capture of an identical fragment REFRESHES the preview
            # metadata (the schema may have evolved; the content is the same,
            # so the hash and the dedupe stay untouched).
            if node_meta is not None:
                dup[0]["nodeMeta"] = node_meta
                _write_index(items, wf)
            return web.json_response({"ok": True, "item": dup[0], "moved": True})
        item = {"id": uuid.uuid4().hex[:12], "type": entry_type, "hash": h,
                "text": text, "size": size}
        if name:
            item["name"] = name
        if tab:
            item["tab"] = tab
        if node_meta is not None:
            item["nodeMeta"] = node_meta
        if size > TEXT_INLINE_LIMIT:
            _ensure_dirs(wf)
            blob_name = item["id"] + ".txt"
            with open(os.path.join(_items_dir(wf), blob_name), "wb") as f:
                f.write(text.encode("utf-8"))
            item["file"] = blob_name
            del item["text"]
        item["created"] = int(time.time())
        items.insert(0, item)
        _evict(items, wf)
        _write_index(items, wf)
    return web.json_response({"ok": True, "item": item, "moved": False})



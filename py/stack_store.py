@PromptServer.instance.routes.post("/settings_hub/stack/patch")
async def stack_patch(request):
    """v72: edit ONE entry's metadata: rename, tags, pin, usage counter.
    Body: JSON {id, name?, tags?, pinned?, uses?, bumpUses?, tab?} (v79 adds
    tab: set/clear the display group). Missing keys leave the entry
    untouched. The response carries the updated entry so the client can
    mirror the server truth instead of guessing."""
    try:
        body = await request.json()
    except Exception:
        return web.json_response({"ok": False, "error": "bad json"}, status=400)
    if not isinstance(body, dict):
        return web.json_response({"ok": False, "error": "bad body"}, status=400)
    item_id = body.get("id") or ""
    if not _ID_RE.match(item_id):
        return web.json_response({"ok": False, "error": "bad id"}, status=400)
    wf, err = _wf_from(request)
    if err is not None:
        return err
    async with _lock:
        items = _read_index(wf)
        it = next((x for x in items if x.get("id") == item_id), None)
        if it is None:
            return web.json_response({"ok": True, "gone": True})
        if "name" in body:
            nm = _sanitize_name(body.get("name"))
            if nm:
                it["name"] = nm
            else:
                it.pop("name", None)
        if "tags" in body:
            tags = body.get("tags")
            clean = []
            if isinstance(tags, list):
                for t in tags:
                    if not isinstance(t, str):
                        continue
                    t = _sanitize_name(t)
                    if t and t.lower() not in [x.lower() for x in clean]:
                        clean.append(t)
                    if len(clean) >= MAX_TAGS:
                        break
            if clean:
                it["tags"] = clean
            else:
                it.pop("tags", None)
        if "pinned" in body:
            it["pinned"] = bool(body.get("pinned"))
        if "tab" in body:
            tb = _sanitize_tab(body.get("tab"))
            if tb:
                it["tab"] = tb
            else:
                it.pop("tab", None)  # v79: empty string = back to "All"
        if "uses" in body:
            try:
                it["uses"] = max(0, min(1_000_000, int(body.get("uses"))))
            except (TypeError, ValueError):
                pass
        if body.get("bumpUses"):
            it["uses"] = min(1_000_000, int(it.get("uses", 0)) + 1)
        _write_index(items, wf)
    return web.json_response({"ok": True, "item": it})


@PromptServer.instance.routes.post("/settings_hub/stack/reorder")
async def stack_reorder(request):
    """v80: store the client's manual ORDER (the move mode toggle in the
    panel: drag cards to sort). Body: JSON {order: [id, ...]} - the FULL new
    order, top-first. Only ids that exist in this store are applied, in the
    payload's order; entries NOT mentioned keep their relative order at the
    END (a stale/partial payload can never lose entries), and the blobs plus
    every other field are untouched. An absent/empty order is an error -
    a bad client must not wipe the order by accident. ?wf= scopes it."""
    try:
        body = await request.json()
    except Exception:
        return web.json_response({"ok": False, "error": "bad json"}, status=400)
    order = body.get("order") if isinstance(body, dict) else None
    if not isinstance(order, list) or not order:
        return web.json_response({"ok": False, "error": "bad order"}, status=400)
    if len(order) > MAX_ITEMS * 4:
        return web.json_response({"ok": False, "error": "order too large"}, status=413)
    wf, err = _wf_from(request)
    if err is not None:
        return err
    async with _lock:
        items = _read_index(wf)
        by_id = {it.get("id"): it for it in items}
        seen = set()
        new = []
        for raw in order:
            if not isinstance(raw, str) or raw in seen:
                continue
            it = by_id.get(raw)
            if it is not None:
                new.append(it)
                seen.add(raw)
        # never lose entries: whatever the payload did not mention keeps its
        # relative order at the end (a stale client list is a subset at worst)
        new.extend(it for it in items if it.get("id") not in seen)
        _write_index(new, wf)
        out = [dict(it) for it in new]
    return web.json_response({"ok": True, "items": out})


@PromptServer.instance.routes.delete("/settings_hub/stack/item/{item_id}")
async def stack_delete(request):
    item_id = request.match_info.get("item_id", "")
    if not _ID_RE.match(item_id):
        return web.json_response({"ok": False, "error": "bad id"}, status=400)
    wf, err = _wf_from(request)
    if err is not None:
        return err
    async with _lock:
        items = _read_index(wf)
        found = next((it for it in items if it.get("id") == item_id), None)
        if found is None:
            return web.json_response({"ok": True, "gone": True})
        items.remove(found)
        _unlink_blob(found.get("file"), wf)
        _write_index(items, wf)
    return web.json_response({"ok": True})


@PromptServer.instance.routes.post("/settings_hub/stack/clear")
async def stack_clear(request):
    """v77: clears ONE store - the shared one, or the ?wf= workflow's own.
    It never touches the other scopes (each scope's entries stay in it).
    v79: with ?tab=<name> only THAT tab's entries are wiped - the other tabs
    and the ungrouped entries stay. A present-but-empty ?tab= is an error
    (an accidental whole-store wipe must not hide behind an empty value)."""
    wf, err = _wf_from(request)
    if err is not None:
        return err
    has_tab = "tab" in request.query
    tab = _sanitize_tab(request.query.get("tab")) if has_tab else None
    if has_tab and not tab:
        return web.json_response({"ok": False, "error": "bad tab"}, status=400)
    async with _lock:
        items = _read_index(wf)
        if has_tab:
            killed = [it for it in items if it.get("tab") == tab]
            items = [it for it in items if it.get("tab") != tab]
            for it in killed:
                _unlink_blob(it.get("file"), wf)
            removed = len(killed)
        else:
            removed = len(items)
            for it in items:
                _unlink_blob(it.get("file"), wf)
            items = []
        _write_index(items, wf)
    return web.json_response({"ok": True, "removed": removed, "tab": tab})


@PromptServer.instance.routes.get("/settings_hub/stack/file/{name}")
async def stack_file(request):
    name = request.match_info.get("name", "")
    if not _NAME_RE.match(name):
        return web.json_response({"ok": False, "error": "bad name"}, status=400)
    wf, err = _wf_from(request)
    if err is not None:
        return err
    root = os.path.abspath(_items_dir(wf))
    path = os.path.abspath(os.path.join(root, name))
    if not path.startswith(root + os.sep) or not os.path.isfile(path):
        return web.json_response({"ok": False, "error": "not found"}, status=404)
    ext = os.path.splitext(name)[1].lower().lstrip(".")
    ctype = _FILE_MIME.get(ext, "application/octet-stream")
    headers = {"Content-Type": ctype, "Cache-Control": "no-store"}
    # v71: video/audio must be seekable - FileResponse handles range
    # requests natively, but only when the client is allowed to ask.
    if ext in _VID_EXT or ext in _AUD_EXT:
        headers["Accept-Ranges"] = "bytes"
    return web.FileResponse(path, headers=headers)

@PromptServer.instance.routes.post("/settings_hub/stack/patch")
async def stack_patch(request):
    """v72: edit ONE entry's metadata: rename, tags, pin, usage counter.
    Body: JSON {id, name?, tags?, pinned?, uses?, bumpUses?, tab?} (v79 adds
    tab: set/clear the display group). v97 adds `text`: edit the content of
    a TEXT entry (the Full text view editor). Only type:"text" accepts it -
    media blobs and node fragments stay immutable here; a file-backed text
    (>100 KB at creation) rewrites its .txt blob in place, an inline text
    that grew past TEXT_INLINE_LIMIT is promoted to a blob; size+hash follow
    the new content so dedupe stays honest. Missing keys leave the entry
    untouched. The response carries the updated entry so the client can
    mirror the server truth instead of guessing."""
    try:
        body = await request.json()
    except Exception:
        return web.json_response({"ok": False, "error": "bad json"}, status=400)
    if not isinstance(body, dict):
        return web.json_response({"ok": False, "error": "bad body"}, status=400)
    item_id = body.get("id") or ""
    if not _ID_RE.match(item_id):
        return web.json_response({"ok": False, "error": "bad id"}, status=400)
    wf, err = _wf_from(request)
    if err is not None:
        return err
    async with _lock:
        items = _read_index(wf)
        it = next((x for x in items if x.get("id") == item_id), None)
        if it is None:
            return web.json_response({"ok": True, "gone": True})
        if "name" in body:
            nm = _sanitize_name(body.get("name"))
            if nm:
                it["name"] = nm
            else:
                it.pop("name", None)
        if "tags" in body:
            tags = body.get("tags")
            clean = []
            if isinstance(tags, list):
                for t in tags:
                    if not isinstance(t, str):
                        continue
                    t = _sanitize_name(t)
                    if t and t.lower() not in [x.lower() for x in clean]:
                        clean.append(t)
                    if len(clean) >= MAX_TAGS:
                        break
            if clean:
                it["tags"] = clean
            else:
                it.pop("tags", None)
        if "pinned" in body:
            it["pinned"] = bool(body.get("pinned"))
        if "tab" in body:
            tb = _sanitize_tab(body.get("tab"))
            if tb:
                it["tab"] = tb
            else:
                it.pop("tab", None)  # v79: empty string = back to "All"
        # v99: store/refresh the PREVIEW metadata of a NODE FRAGMENT (the
        # lazy backfill path for entries captured before v99, file-backed
        # ones included). Strictly "nodes"-only and whitelist-sanitized -
        # a refusal answers 400 so the client knows the backfill failed
        # (a silent ignore would look like a lost card).
        if "nodeMeta" in body:
            if it.get("type") != "nodes":
                return web.json_response(
                    {"ok": False, "error": "nodeMeta allowed for nodes entries only"},
                    status=400)
            nm = _sanitize_node_meta(body.get("nodeMeta"))
            if nm is None:
                return web.json_response(
                    {"ok": False, "error": "bad nodeMeta"}, status=400)
            it["nodeMeta"] = nm
        # v97: edit the CONTENT of a text entry (the Full text view editor).
        # Refusals answer with an error so the client can keep the textarea
        # open (a silent ignore would look like a lost save).
        if "text" in body:
            if it.get("type") != "text":
                return web.json_response(
                    {"ok": False, "error": "text edit allowed for text entries only"},
                    status=400)
            nt = body.get("text")
            if not isinstance(nt, str) or not nt.strip():
                return web.json_response({"ok": False, "error": "empty text"}, status=400)
            if len(nt) > MAX_TEXT_CHARS:
                return web.json_response({"ok": False, "error": "text too large"}, status=413)
            data = nt.encode("utf-8", "ignore")
            if it.get("file"):
                # file-backed text (>TEXT_INLINE_LIMIT at creation): rewrite
                # the .txt blob in place, keep the backing
                _ensure_dirs(wf)
                with open(os.path.join(_items_dir(wf), it["file"]), "wb") as f:
                    f.write(data)
            elif len(data) > TEXT_INLINE_LIMIT:
                # inline text grew past the limit - promote to a blob
                _ensure_dirs(wf)
                blob_name = it["id"] + ".txt"
                with open(os.path.join(_items_dir(wf), blob_name), "wb") as f:
                    f.write(data)
                it["file"] = blob_name
                it.pop("text", None)
            else:
                it["text"] = nt
            it["size"] = len(data)
            it["hash"] = _hash_bytes(data)
        if "uses" in body:
            try:
                it["uses"] = max(0, min(1_000_000, int(body.get("uses"))))
            except (TypeError, ValueError):
                pass
        if body.get("bumpUses"):
            it["uses"] = min(1_000_000, int(it.get("uses", 0)) + 1)
        _write_index(items, wf)
    return web.json_response({"ok": True, "item": it})


@PromptServer.instance.routes.post("/settings_hub/stack/reorder")
async def stack_reorder(request):
    """v80: store the client's manual ORDER (the move mode toggle in the
    panel: drag cards to sort). Body: JSON {order: [id, ...]} - the FULL new
    order, top-first. Only ids that exist in this store are applied, in the
    payload's order; entries NOT mentioned keep their relative order at the
    END (a stale/partial payload can never lose entries), and the blobs plus
    every other field are untouched. An absent/empty order is an error -
    a bad client must not wipe the order by accident. ?wf= scopes it."""
    try:
        body = await request.json()
    except Exception:
        return web.json_response({"ok": False, "error": "bad json"}, status=400)
    order = body.get("order") if isinstance(body, dict) else None
    if not isinstance(order, list) or not order:
        return web.json_response({"ok": False, "error": "bad order"}, status=400)
    if len(order) > MAX_ITEMS * 4:
        return web.json_response({"ok": False, "error": "order too large"}, status=413)
    wf, err = _wf_from(request)
    if err is not None:
        return err
    async with _lock:
        items = _read_index(wf)
        by_id = {it.get("id"): it for it in items}
        seen = set()
        new = []
        for raw in order:
            if not isinstance(raw, str) or raw in seen:
                continue
            it = by_id.get(raw)
            if it is not None:
                new.append(it)
                seen.add(raw)
        # never lose entries: whatever the payload did not mention keeps its
        # relative order at the end (a stale client list is a subset at worst)
        new.extend(it for it in items if it.get("id") not in seen)
        _write_index(new, wf)
        out = [dict(it) for it in new]
    return web.json_response({"ok": True, "items": out})



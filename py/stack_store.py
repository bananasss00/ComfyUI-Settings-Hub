def _read_index(wf=None):
    try:
        with open(_index_path(wf), "r", encoding="utf-8") as f:
            data = json.load(f)
        if isinstance(data, list):
            return [it for it in data if isinstance(it, dict) and isinstance(it.get("id"), str)]
    except Exception:
        pass
    return []


def _write_index(items, wf=None):
    _ensure_dirs(wf)
    tmp = _index_path(wf) + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(items, f, ensure_ascii=False)
    os.replace(tmp, _index_path(wf))


# ---------------------------------------------------------------------------
# Mutations (call under _lock)
# ---------------------------------------------------------------------------

def _hash_bytes(b):
    return hashlib.sha1(b).hexdigest()[:16]


def _entry_size(it):
    if it.get("type") == "text":
        return len(it.get("text", "").encode("utf-8", "ignore"))
    return int(it.get("size", 0) or 0)


def _evict(items, wf=None):
    """Drop the oldest tail until count/size caps hold; pinned entries are
    reserved (the field arrives in v72, guarded here already). The caps are
    PER STORE (v77): every workflow scope gets its own budget."""
    def droppable():
        alive = [it for it in items if not it.get("pinned")]
        return alive[-1] if alive else None

    while len(items) > MAX_ITEMS:
        victim = droppable()
        if victim is None:
            break
        items.remove(victim)
        _unlink_blob(victim.get("file"), wf)
    total = sum(_entry_size(it) for it in items)
    while total > MAX_TOTAL_BYTES:
        victim = droppable()
        if victim is None:
            break
        items.remove(victim)
        _unlink_blob(victim.get("file"), wf)
        total -= _entry_size(victim)



STACK_SERVER_VERSION = "v83"


@PromptServer.instance.routes.get("/settings_hub/stack/health")
async def stack_health(request):
    """v76 self-diagnosis for the Paste Stack panel (and humans): proves the
    Python routes are alive, reports where the storage lives, whether it is
    WRITABLE (a probe file is written+deleted inside items/) and how many
    entries the index currently holds. v77 adds `workflows` - the number of
    per-workflow stores. Never throws: every check degrades to a false/empty
    field."""
    _ensure_dirs()
    writable = False
    try:
        probe = os.path.join(_items_dir(), ".health_probe")
        with open(probe, "w", encoding="utf-8") as f:
            f.write("ok")
        os.unlink(probe)
        writable = True
    except Exception:
        writable = False
    try:
        n_items = len(_read_index())
    except Exception:
        n_items = -1
    return web.json_response({
        "ok": True,
        "version": STACK_SERVER_VERSION,
        "dir": _stack_root(),
        "writable": writable,
        "items": n_items,
        "workflows": _workflow_count(),
    })


@PromptServer.instance.routes.post("/settings_hub/stack/item")
async def stack_add_text(request):
    """Add a TEXT entry. Body: JSON {text}. Text lives inline in the index
    unless it exceeds TEXT_INLINE_LIMIT - then it is stored as a .txt blob."""
    try:
        body = await request.json()
    except Exception:
        return web.json_response({"ok": False, "error": "bad json"}, status=400)
    text = body.get("text") if isinstance(body, dict) else None
    if not isinstance(text, str) or not text.strip():
        return web.json_response({"ok": False, "error": "empty text"}, status=400)
    if len(text) > MAX_TEXT_CHARS:
        return web.json_response({"ok": False, "error": "text too large"}, status=413)
    name = _sanitize_name(body.get("name")) if isinstance(body, dict) else None
    tab = _sanitize_tab(body.get("tab")) if isinstance(body, dict) else None
    wf, err = _wf_from(request)
    if err is not None:
        return err
    size = len(text.encode("utf-8", "ignore"))
    async with _lock:
        items = _read_index(wf)
        h = _hash_bytes(text.encode("utf-8"))
        dup = _touch_dup(items, h, wf)
        if dup is not None:
            # v71: a fresh drop of the same content may carry a better name.
            if name and not dup[0].get("name"):
                dup[0]["name"] = name
                _write_index(items, wf)
            # v79: re-adding into a tab groups the existing entry too - but a
            # tab already on the entry is NEVER overridden by a re-capture.
            if tab and not dup[0].get("tab"):
                dup[0]["tab"] = tab
                _write_index(items, wf)
            return web.json_response({"ok": True, "item": dup[0], "moved": True})
        item = {"id": uuid.uuid4().hex[:12], "type": "text", "hash": h,
                "text": text, "size": size}
        if name:
            item["name"] = name
        if tab:
            item["tab"] = tab
        if size > TEXT_INLINE_LIMIT:
            _ensure_dirs(wf)
            blob_name = item["id"] + ".txt"
            with open(os.path.join(_items_dir(wf), blob_name), "wb") as f:
                f.write(text.encode("utf-8"))
            item["file"] = blob_name
            del item["text"]
        item["created"] = int(time.time())
        items.insert(0, item)
        _evict(items, wf)
        _write_index(items, wf)
    return web.json_response({"ok": True, "item": item, "moved": False})


@PromptServer.instance.routes.post("/settings_hub/stack/image")
async def stack_add_image(request):
    """Add an IMAGE entry. Body: raw bytes, ?ext=png|jpg|jpeg|webp|gif|bmp and
    an optional ?name= display name (v71: the OS-helper payload keeps its
    file name). A duplicate (same bytes hash) moves the existing entry to the
    top and the new payload is discarded without touching the stored blob."""
    ext = (request.query.get("ext") or "png").lower().lstrip(".")
    if ext not in _IMG_EXT:
        return web.json_response({"ok": False, "error": "bad ext"}, status=400)
    name = _sanitize_name(request.query.get("name"))
    tab = _sanitize_tab(request.query.get("tab"))
    wf, err = _wf_from(request)
    if err is not None:
        return err
    payload = await request.read()
    if not payload:
        return web.json_response({"ok": False, "error": "empty payload"}, status=400)
    if len(payload) > MAX_IMAGE_BYTES:
        return web.json_response({"ok": False, "error": "image too large"}, status=413)
    async with _lock:
        items = _read_index(wf)
        h = _hash_bytes(payload)
        dup = _touch_dup(items, h, wf)
        if dup is not None:
            if name and not dup[0].get("name"):
                dup[0]["name"] = name
                _write_index(items, wf)
            return web.json_response({"ok": True, "item": dup[0], "moved": True})
        item_id = uuid.uuid4().hex[:12]
        name2 = item_id + "." + ext
        _ensure_dirs(wf)
        with open(os.path.join(_items_dir(wf), name2), "wb") as f:
            f.write(payload)
        item = {"id": item_id, "type": "image", "hash": h,
                "file": name2, "size": len(payload), "created": int(time.time())}
        if name:
            item["name"] = name
        if tab:
            item["tab"] = tab
        items.insert(0, item)
        _evict(items, wf)
        _write_index(items, wf)
    return web.json_response({"ok": True, "item": item, "moved": False})


